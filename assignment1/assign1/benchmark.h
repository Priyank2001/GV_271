#ifndef BENCHMARK_H
#define BENCHMARK_H

#include <iomanip>

// Include this file exactly once, as the LAST line of main.cpp -- after every
// global (model, indices, currentMode, numActivePlanes, VAO, VBO, EBO,
// colorVBO, normalVBO, preppedVAO, preppedPosVBO) and every function it calls
// (readOffFile, ComputeModelTransform, setupCamera, createVertexBuffers,
// buildPreppedWholeMesh, FreeOffModel, rebuildWedgeGeometryDefs) is already
// defined above it in the same translation unit. This header is not designed
// to be compiled as a separate .cpp -- it relies on that ambient scope.

bool benchmarking = false;

std::vector<std::string> benchMeshPaths = {
    "../../1GRM_1.off","../../1GRM_2.off","../../1GRM_4.off","../../1GRM_8.off","../../1GRM_16.off",
    "../../2OAR_1.off","../../2OAR_2.off","../../2OAR_4.off","../../2OAR_8.off","../../2OAR_16.off",
    "../../3SY7_1.off","../../3SY7_2.off","../../3SY7_4.off","../../3SY7_8.off","../../3SY7_16.off"
};
const int benchPlaneCounts[] = {1,4,10};
const int numBenchPlaneCounts = 3;
int benchMeshIdx = 0;
int benchPlaneIdx = 0;
enum BenchImpl { BI_CPU, BI_GPU };
BenchImpl benchImpl = BI_CPU;
int benchPhaseStartMs = 0;
const int benchWarmupMs = 300;
const int benchMeasureMs = 700;
bool benchInMeasurePhase = false;
long benchMeasureFrameCount = 0;

struct BenchResult { std::string meshFile; int vertexCount, triangleCount, planes; std::string impl; double fps; };
std::vector<BenchResult> benchResults;

void freeMeshGLBuffers(){
    if(VAO) glDeleteVertexArrays(1,&VAO);
    if(VBO) glDeleteBuffers(1,&VBO);
    if(EBO) glDeleteBuffers(1,&EBO);
    if(colorVBO) glDeleteBuffers(1,&colorVBO);
    if(normalVBO) glDeleteBuffers(1,&normalVBO);
    if(preppedVAO) glDeleteVertexArrays(1,&preppedVAO);
    if(preppedPosVBO) glDeleteBuffers(1,&preppedPosVBO);
    if(flatVAO) glDeleteVertexArrays(1,&flatVAO);
    if(flatPosVBO) glDeleteBuffers(1,&flatPosVBO);
    if(flatNrmVBO) glDeleteBuffers(1,&flatNrmVBO);
    VAO=VBO=EBO=colorVBO=normalVBO=preppedVAO=preppedPosVBO=0;
    flatVAO=flatPosVBO=flatNrmVBO=0;
}

void loadMeshAtPath(const std::string& path){
    freeMeshGLBuffers();
    if(model) FreeOffModel(model);
    model = readOffFile((char*)path.c_str());
    ComputeModelTransform();
    setupCamera();
    createVertexBuffers();
    buildPreppedWholeMesh();
    buildFlatShadedMesh();
    std::cout << "[bench] loaded " << path << " (" << model->numberOfVertices
              << " verts, " << indices.size()/3 << " tris)\n";
}

void writeLatexTable(const std::string& path){
    std::ofstream out(path);
    if(!out){ std::cerr << "[bench] failed to open " << path << "\n"; return; }

    out << "% Auto-generated by the benchmark sweep -- \\input{" << path << "} directly.\n";
    out << "\\begin{table}[H]\n\\centering\n\\footnotesize\n"
        << "\\renewcommand{\\arraystretch}{0.92}\n"
        << "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
        << "Mesh & Vertices & Triangles & Planes ($M$) & CPU FPS & GPU FPS \\\\\n\\midrule\n";

    for(size_t i = 0; i < benchResults.size(); i++){
        if(benchResults[i].impl != "CPU") continue;   // pair each CPU row with its matching GPU row
        double gpuFps = -1.0;
        for(size_t j = 0; j < benchResults.size(); j++){
            if(benchResults[j].impl == "GPU" &&
               benchResults[j].meshFile == benchResults[i].meshFile &&
               benchResults[j].planes == benchResults[i].planes){
                gpuFps = benchResults[j].fps; break;
            }
        }
        std::string name = benchResults[i].meshFile;
        size_t slash = name.find_last_of("/\\");
        if(slash != std::string::npos) name = name.substr(slash+1);
        size_t dot = name.find_last_of('.');
        if(dot != std::string::npos) name = name.substr(0, dot);

        out << "\\texttt{";
        for(char c : name) out << (c=='_' ? "\\_" : std::string(1,c));
        out << "} & " << benchResults[i].vertexCount << " & " << benchResults[i].triangleCount
            << " & " << benchResults[i].planes << " & "
            << std::fixed << std::setprecision(1) << benchResults[i].fps << " & ";
        if(gpuFps >= 0.0) out << std::fixed << std::setprecision(1) << gpuFps;
        else out << "--";
        out << " \\\\\n";
    }
    out << "\\bottomrule\n\\end{tabular}\n"
        << "\\caption{Measured FPS across mesh resolutions and active cutting planes, CPU vs.\\ GPU wedge slicing.}\n"
        << "\\end{table}\n";
    std::cout << "[bench] LaTeX table written to " << path << "\n";
}

void finishBenchmark(){
    benchmarking = false;
    currentMode = MODE_WHOLE;
    std::cout << "[bench] complete -- " << benchResults.size() << " data points\n";
    writeLatexTable("../report/benchmark_t.tex");
}

void enterBenchCell(){
    numActivePlanes = benchPlaneCounts[benchPlaneIdx];
    rebuildWedgeGeometryDefs();
    currentMode = (benchImpl == BI_CPU) ? MODE_CPU_SLICE : MODE_GPU_SLICE;
    benchInMeasurePhase = false;
    benchPhaseStartMs = glutGet(GLUT_ELAPSED_TIME);
    benchMeasureFrameCount = 0;
}

void advanceBenchCell(){
    if(benchImpl == BI_CPU){
        benchImpl = BI_GPU;
    } else {
        benchImpl = BI_CPU;
        benchPlaneIdx++;
        if(benchPlaneIdx >= numBenchPlaneCounts){
            benchPlaneIdx = 0;
            benchMeshIdx++;
            if(benchMeshIdx >= (int)benchMeshPaths.size()){ finishBenchmark(); return; }
            loadMeshAtPath(benchMeshPaths[benchMeshIdx]);
        }
    }
    enterBenchCell();
}

void startBenchmark(){
    if(benchMeshPaths.empty() || benchmarking) return;
    benchmarking = true;
    benchResults.clear();
    benchMeshIdx = 0; benchPlaneIdx = 0; benchImpl = BI_CPU;
    loadMeshAtPath(benchMeshPaths[0]);
    enterBenchCell();
    std::cout << "[bench] started: " << benchMeshPaths.size() << " meshes x "
              << numBenchPlaneCounts << " plane counts x 2 implementations\n";
}

void benchmarkTick(){
    int nowMs = glutGet(GLUT_ELAPSED_TIME);
    int elapsed = nowMs - benchPhaseStartMs;
    if(!benchInMeasurePhase){
        if(elapsed >= benchWarmupMs){
            benchInMeasurePhase = true;
            benchPhaseStartMs = nowMs;
            benchMeasureFrameCount = 0;
        }
        return;
    }
    benchMeasureFrameCount++;
    if(elapsed >= benchMeasureMs){
        double fps = 1000.0 * benchMeasureFrameCount / (double)elapsed;
        benchResults.push_back({ benchMeshPaths[benchMeshIdx], model->numberOfVertices,
                                  (int)(indices.size()/3), numActivePlanes,
                                  (benchImpl==BI_CPU?"CPU":"GPU"), fps });
        std::cout << "[bench] " << benchMeshPaths[benchMeshIdx] << " tris=" << indices.size()/3
                  << " planes=" << numActivePlanes << " " << (benchImpl==BI_CPU?"CPU":"GPU")
                  << " -> " << fps << " FPS\n";
        advanceBenchCell();
    }
}

#endif // BENCHMARK_H